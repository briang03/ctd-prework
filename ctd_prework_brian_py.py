# this script simulates a simple cafe order where it prompts the user to order
# either a drink, pastry, or both
# if both drink and pastry is ordered then there is a discount of $1

drink_order = {
    "coffee": 3,
    "esspresso": 4,
    "matcha": 6,
    "lemonade": 4,
    "einspanner": 7
}
pastry_order = {
    "croissant": 2,
    "muffin": 3,
    "donut": 4,
    "cookie": 5,
    "bagel": 2
}
price=0
discount=0
drink = input("what drink would you like?").lower()
pastry = input("what pastry would you like?").lower()

if drink in drink_order:
  price+=drink_order[drink]
  discount+=1
else:
  print("we dont have that drink")

if pastry in pastry_order:
  price+=pastry_order[pastry]
  discount+=1
else:
  print("we dont have that pastry")

if discount==2:
  price-=1
  print("Since you ordered both a drink and a pastry get $1 off your order")

print(f"Your total is: ${price:.2f}")

# Example run 1
# Inputs: Coffee, Bagel
# Output: Since you ordered both a drink and a pastry get $1 off your order
# Your total is: $4.00

